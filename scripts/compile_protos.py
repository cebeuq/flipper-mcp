"""Download the Flipper Zero protobuf schema and compile it to Python.

Fetches the 8 .proto files from flipperdevices/flipperzero-protobuf (dev branch)
into ../proto/, then runs grpc_tools.protoc to emit *_pb2.py into
../flipper_mcp/rpc/proto/. The generated modules cross-import each other flatly
(e.g. `import storage_pb2`), so flipper_mcp/rpc/proto/__init__.py puts its own
directory on sys.path to make those imports resolve.
"""
import os
import sys
import urllib.request

BRANCH = "dev"
BASE = f"https://raw.githubusercontent.com/flipperdevices/flipperzero-protobuf/{BRANCH}/"
PROTOS = [
    "flipper", "storage", "system", "application",
    "gui", "gpio", "property", "desktop",
]

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PROTO_SRC = os.path.join(ROOT, "proto")
PROTO_OUT = os.path.join(ROOT, "flipper_mcp", "rpc", "proto")


def download():
    os.makedirs(PROTO_SRC, exist_ok=True)
    for name in PROTOS:
        url = BASE + name + ".proto"
        dst = os.path.join(PROTO_SRC, name + ".proto")
        req = urllib.request.Request(url, headers={"User-Agent": "flipper-mcp/0.1"})
        with urllib.request.urlopen(req, timeout=30) as r:
            data = r.read()
        with open(dst, "wb") as f:
            f.write(data)
        print(f"  downloaded {name}.proto ({len(data)} bytes)")


def compile_all():
    os.makedirs(PROTO_OUT, exist_ok=True)
    from grpc_tools import protoc
    args = [
        "grpc_tools.protoc",
        f"-I{PROTO_SRC}",
        f"--python_out={PROTO_OUT}",
    ] + [os.path.join(PROTO_SRC, f"{n}.proto") for n in PROTOS]
    rc = protoc.main(args)
    if rc != 0:
        raise SystemExit(f"protoc failed with code {rc}")
    # Ensure the output dir is an importable package with a sys.path shim.
    init_path = os.path.join(PROTO_OUT, "__init__.py")
    with open(init_path, "w", encoding="utf-8") as f:
        f.write(
            '"""Compiled Flipper protobuf messages.\n\n'
            "Generated by scripts/compile_protos.py. The *_pb2 modules import each\n"
            "other by bare name, so we put this directory on sys.path.\n"
            '"""\n'
            "import os as _os\n"
            "import sys as _sys\n"
            "_here = _os.path.dirname(_os.path.abspath(__file__))\n"
            "if _here not in _sys.path:\n"
            "    _sys.path.insert(0, _here)\n"
        )
    print(f"  compiled -> {PROTO_OUT}")


def main():
    print("Downloading protos...")
    download()
    print("Compiling protos...")
    compile_all()
    # Smoke test import.
    sys.path.insert(0, ROOT)
    from flipper_mcp.rpc.proto import flipper_pb2  # noqa: F401
    m = flipper_pb2.Main()
    m.command_id = 1
    print(f"  smoke test OK: Main has fields {[f.name for f in m.DESCRIPTOR.fields][:4]}...")
    return 0


if __name__ == "__main__":
    sys.exit(main())
